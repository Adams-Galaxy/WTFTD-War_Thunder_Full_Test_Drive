class CdkError(Exception):
    pass


def game_data_root() -> str:
    """Game-data path used for locally written CDK assets.

    The Linux client looks up custom files in the lower-case ``gamedata`` tree.
    Keep the spelling documented by the CDK on Windows and macOS, whose usual
    file systems are case-insensitive.
    """
    return "gamedata" if sys.platform.startswith("linux") else "gameData"


def _unit_dir(category: str) -> str:
    folders = {
        "ground": "units/tankModels",
        "air": "flightModels",
        "heli": "flightModels",
        "boat": "units/ships",
        "ship": "units/ships",
    }
    try:
        return f"{game_data_root()}/{folders[category]}"
    except KeyError:
        raise CdkError("Unsupported vehicle type") from None


def _r(v) -> str:
    v = float(v)
    s = repr(round(v, 6))
    return s[:-2] if s.endswith(".0") else s


def _num(d: dict, key: str, lo: float, hi: float):
    v = d.get(key)
    if v in (None, ""):
        return None
    try:
        v = float(v)
    except (TypeError, ValueError):
        raise CdkError(f"Invalid value for {key}")
    if not lo <= v <= hi:
        raise CdkError(f"{key} must be between {lo} and {hi}")
    return v


def _blk_value(typ: str, v) -> str:
    if typ == "r":
        return _r(v)
    if typ == "i":
        return str(int(v))
    if typ == "b":
        return "yes" if v else "no"
    if typ == "t":
        return f'"{v}"'
    if typ in ("p2", "p3", "p4"):
        return ", ".join(_r(x) for x in v)
    raise CdkError(f"Unknown value type {typ}")


class Blk:
    """Tiny writer for override files."""

    def __init__(self):
        self.lines: list[str] = []
        self.ind = 0

    def line(self, s: str):
        self.lines.append("  " * self.ind + s)

    def open(self, name: str):
        self.line(f'"@override:{name}"{{')
        self.ind += 1

    def close(self):
        self.ind -= 1
        self.line("}")

    def real(self, name: str, v):
        self.line(f'"@override:{name}":r={_r(v)}')

    def plain(self, name: str):
        """A block the file it includes doesn't have."""
        self.line(f"{name}{{")
        self.ind += 1

    def int(self, name: str, v):
        self.line(f'"@override:{name}":i={int(v)}')

    def p2(self, name: str, v):
        self.line(f'"@override:{name}":p2={_r(v[0])}, {_r(v[1])}')

    def p3(self, name: str, v):
        self.line(f'"@override:{name}":p3={_r(v[0])}, {_r(v[1])}, {_r(v[2])}')

    def text(self, name: str, v: str):
        self.line(f'"@override:{name}":t="{v}"')

    def __str__(self):
        return "\n".join(self.lines) + "\n"


def _header(what: str, include: str) -> Blk:
    b = Blk()
    b.line(f"{MARKER} - {what} - {time.strftime('%Y-%m-%d %H:%M')}")
    b.line(f'include "{INCLUDE_ROOT}{include}"')
    b.line("")
    return b


def _shell_block(b: Blk, sm: dict):
    """Writes overrides for one bullet block from {v, m, e, h, l}."""
    b.open("bullet")
    if sm.get("v") is not None:
        b.real("speed", sm["v"])
    if sm.get("m") is not None:
        b.real("mass", sm["m"])
    if sm.get("e") is not None:
        b.real("explosiveMass", sm["e"])
    if sm.get("h") is not None:
        b.open("cumulativeDamage")
        b.real("armorPower", sm["h"])
        b.close()
    if sm.get("l") is not None:
        b.open("damage")
        b.open("kinetic")
        b.real("lanzOdermattWorkingLength", sm["l"])
        b.close()
        b.close()
    b.close()


def _clean_shells(shells: dict, group: dict) -> dict:
    """Validates {set_id: {v,m,e,h,l}} against the gun's known ammo sets."""
    known = {o["id"]: o.get("s", {}) for o in group.get("opts", [])}
    out = {}
    for sid, vals in (shells or {}).items():
        if sid not in known or not isinstance(vals, dict):
            continue
        base = known[sid]
        sm = {}
        for k, lo, hi in (("v", 1, 20000), ("m", 0.001, 10000), ("e", 0, 10000), ("h", 0, 100000), ("l", 1, 100000)):
            if k in base:
                v = _num(vals, k, lo, hi)
                if v is not None and abs(v - base[k]) > 1e-9:
                    sm[k] = v
        if sm:
            out[sid] = sm
    return out


def _weapon_slots(unit_data: dict | None) -> dict[int, tuple[int, str]]:
    """Slot index -> (1-based position of its WeaponSlot block, bomb emitter of that slot or "")."""
    ws = (unit_data or {}).get("WeaponSlots")
    sl = ws.get("WeaponSlot") if isinstance(ws, dict) else None
    sl = sl if isinstance(sl, list) else [sl] if isinstance(sl, dict) else []
    out = {}
    for pos, s in enumerate(sl, start=1):
        if not isinstance(s, dict) or not isinstance(s.get("index"), int):
            continue
        bomb_em = ""
        wps = s.get("WeaponPreset")
        for wp in wps if isinstance(wps, list) else [wps] if isinstance(wps, dict) else []:
            ws_ = wp.get("Weapon") if isinstance(wp, dict) else None
            for w in ws_ if isinstance(ws_, list) else [ws_] if isinstance(ws_, dict) else []:
                if not bomb_em and isinstance(w, dict) and w.get("trigger") == "bombs" and w.get("external") \
                        and isinstance(w.get("emitter"), str):
                    bomb_em = w["emitter"]
        out[s["index"]] = (pos, bomb_em)
    return out


def _weapon_lines(trigger: str, blk: str, emitter: str, bullets: int | None, ind: str = "", separate: bool = False) -> list[str]:
    lines = ["Weapon{", f'  trigger:t="{trigger}"', f'  blk:t="{blk}"', f'  emitter:t="{emitter}"']
    if bullets:
        lines.append(f"  bullets:i={bullets}")
    lines.append("  external:b=yes")
    if separate:  # as the game's own pylon presets: one pylon at a time, not every pylon with that trigger at once
        lines.append("  separate:b=yes")
    lines.append("}")
    return [ind + s for s in lines]


# Pylon weapons, modified ({"w": key, "n": count, "mod": {...}}): the weapon file's payload block by folder,
# and what each "mod" key overrides there (absolute values; "g" / "gReq" only on guided weapons: overload limit,
# autopilot; "kt": a nuclear charge). The page sends only the values the weapon has (server.weapon_base).
PAYLOADS = {"rocketguns": "rocket", "bombguns": "bomb", "torpedoes": "torpedo", "mines": "mine"}
WEAPON_MODS = {
    "e": ("explosiveMass", 0, 1_000_000),  # kg of explosive
    "mass": ("mass", 0.1, 1_000_000),      # kg, the whole weapon
    "force": ("force", 0, 10_000_000),     # N, rocket motor thrust
    "burn": ("timeFire", 0, 600),          # s, rocket motor burn time
    "mach": ("machMax", 0.1, 50),
    "fins": ("finsLatAccel", 0, 1000),     # lateral acceleration the fins can give
    "range": ("maxDistance", 0, 1_000_000),  # m
}
# The explosion the game shows follows the weapon, not its explosive: the one of the game's weapons of that size
# (datamine, explosive mass in kg up to which each effect is used). Bombs: explosionFx; missiles / rockets:
# explosionEffect, and past their biggest, a bomb's explosionFx as well.
BOMB_FX = ((20, "bomb_expl_50kg"), (50, "bomb_expl_100kg"), (130, "bomb_expl_200kg"), (460, "bomb_expl_500kg"),
           (900, "bomb_expl_1000kg"), (float("inf"), "bomb_expl_5000kg"))
ROCKET_FX = ((2, "explosion_midair_rocket_tiny"), (25, "explosion_midair_rocket_small"),
             (100, "explosion_midair_rocket_medium"), (float("inf"), "explosion_midair_rocket_big"))


def _fx(table, kg: float) -> str:
    return next(fx for limit, fx in table if kg <= limit)


# Advanced changes (mod["adv"] = {"rocket/guidance/workTime": {"t": "r", "v": 30}}): any value of the weapon file,
# by its path and type as the datamine shows it (server.weapon_base "tree"). Checked here: names, types, ranges.
ADV_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")
ADV_TEXT = re.compile(r"^[A-Za-z0-9_\-./ ]{0,120}$")
ADV_MAX = 500


def _adv_value(t: str, v):
    """A checked advanced value, or CdkError."""
    import math
    def real(x):
        x = float(x)
        if not math.isfinite(x) or abs(x) > 1e9:
            raise ValueError
        return x
    try:
        if t == "r":
            return real(v)
        if t == "i":
            x = int(v)
            if abs(x) > 2_000_000_000:
                raise ValueError
            return x
        if t == "b":
            if not isinstance(v, bool):
                raise ValueError
            return v
        if t == "t":
            if not isinstance(v, str) or not ADV_TEXT.match(v):
                raise ValueError
            return v
        if t in ("p2", "p3", "p4"):
            if not isinstance(v, list) or len(v) != int(t[1]):
                raise ValueError
            return [real(x) for x in v]
    except (TypeError, ValueError):
        pass
    raise CdkError(f"Invalid advanced value ({t})")


# What a missile needs on a pylon and a launcher's doesn't say, as the game's own air-to-air missiles have it
AIR_GUN = {"rocketGun": True, "preset_cost": 20, "bullets": 1, "shotFreq": 1000.25, "sound": "weapon.rocketgun_132", "helicopterGroup": 2}
AIR_ROCKET = {"statType": "hydra", "dragCx": 0.018, "iconType": "missile_type_b_air_to_air_midrange"}


def airborne(missile: dict, mesh: str, sam: bool, anim: str = "") -> dict:
    """A ground or ship missile or rocket as an aircraft's weapon: a rocketGun holding it in a `rocket` block (see
    builder.launched_rockets). As the game's own, `mesh` on the pylon and `mesh_deployed` in flight (us_starstreak).
    `anim` is the launcher's animation: without an animChar the Aster-30 doesn't show on a pylon (checked in game)."""
    rocket = {**AIR_ROCKET, **{k: v for k, v in missile.items() if k != "mesh"}}
    rocket.setdefault("finsLatAccel", rocket.get("loadFactorMax", 30.0))
    if sam:
        rocket["bulletType"] = "aam"  # what the aircraft's lock and launch logic looks for
    gun = {**AIR_GUN, "mesh": mesh, "mesh_deployed": missile.get("mesh", mesh), "rocket": rocket}
    anim = missile.get("shellAnimChar") or anim
    if anim:
        gun["animChar"] = anim
    return gun


def _apply(node: dict, tree: dict):
    """Sets {path: (type, value)} in a weapon held whole, as _write_tree would override it."""
    for path, (_, v) in tree.items():
        at = node
        for part in path[:-1]:
            at = at.setdefault(part, {})
        at[path[-1]] = v


def _air_copy(w: dict, what: str, mod=None) -> str | None:
    """The text of a surface weapon's aircraft version, with My weapons' changes; None if its launcher can't be read."""
    launcher = load(blk_to_path(w["p"]))
    missile = launched_missile(launcher) or next(iter(launched_rockets(launcher)), None)
    if not missile:
        return None
    bullets = [b for b in launcher.get("bullet", []) if isinstance(b, dict)] if isinstance(launcher.get("bullet"), list) else [launcher.get("bullet")]
    mesh = next((b["mesh"] for b in bullets if isinstance(b, dict) and b.get("mesh")), launcher.get("mesh", ""))
    air = airborne(missile, mesh, w.get("c") == "sam", launcher.get("animChar", ""))
    if isinstance(mod, dict):
        _apply(air, _weapon_changes(w, mod, "rocket"))
    return f"{MARKER} - {what}\n{blk.dumps(air)}"


