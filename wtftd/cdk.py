def _sensors(b: Blk, details: dict, mods: dict, unit_data: dict | None):
    """An aircraft's radar and warning receivers: each `sensor` of the unit names its file. Picked: {its place: another file},
    added: {kind: a file}, for what it doesn't have."""
    own, picks = details.get("se") or [], mods.get("sensors") if isinstance(mods.get("sensors"), dict) else {}
    changes = {int(k): v for k, v in picks.items() if str(k).isdigit() and int(k) < len(own) and SAFE.match(str(v))}
    extra = mods.get("sensorsAdd") if isinstance(mods.get("sensorsAdd"), dict) else {}
    added = [v for v in extra.values() if SAFE.match(str(v))]
    if not changes and not added:
        return
    if "sensors" in (unit_data or {}):
        b.open("sensors")
    else:
        b.plain("sensors")
    for i, key in sorted(changes.items()):
        b.open(f"sensor[{i + 1}]")
        b.text("blk", f"gameData/sensors/{key}.blk")
        b.close()
    for key in added:
        b.line(f'sensor{{ blk:t="gameData/sensors/{key}.blk" }}')
    b.close()


def _avionics(b: Blk, mods: dict, unit_data: dict | None):
    picks = mods.get("avionics") if isinstance(mods.get("avionics"), dict) else {}
    for key in AVIONICS:
        if isinstance(picks.get(key), bool):
            value = "yes" if picks[key] else "no"
            b.line(f'"@override:{key}":b={value}' if key in (unit_data or {}) else f"{key}:b={value}")


def _voices(b: Blk, mods: dict, unit_data: dict | None):
    """The cockpit's warning voice, and a crew voice of the six special vehicles (their unit file names it)."""
    crew, warning = mods.get("crewVoice"), mods.get("warningVoice")
    if crew in CREW_VOICES:
        b.line(f'"@override:specialSpeechLanguage":t="{crew}"' if "specialSpeechLanguage" in (unit_data or {}) else f'specialSpeechLanguage:t="{crew}"')
    if warning in WARNING_VOICES:
        own = (unit_data or {}).get("Sound") or {}
        _write_tree(b, {("Sound", "voiceWarningSystem"): ("t" if "voiceWarningSystem" in own else "+t", warning)})


def _engine_block(fm: dict) -> tuple:
    for key in ("EngineType0", "Engine0"):
        e = fm.get(key)
        if isinstance(e, dict) and isinstance(e.get("Main"), dict) and e["Main"].get("Type"):
            return key, e
    return "", {}


def _copied(mine: dict, theirs: dict, path: tuple) -> dict:
    out = {}
    for k, v in theirs.items():
        p = path + (k,)
        if k in ENGINE_KEEP:
            continue
        if isinstance(v, dict):
            out.update(_copied(mine[k], v, p) if isinstance(mine.get(k), dict) else {})
        elif isinstance(v, (bool, int, float)):
            t = "b" if isinstance(v, bool) else "i" if isinstance(v, int) else "r"
            out[p] = (t if k in mine else f"+{t}", v)
    return out


def _engine_overrides(fm: dict, donor: dict) -> dict:
    """Another aircraft's engine: its values over ours. Jets take jets, propellers propellers: the rest of the flight model
    (nozzles, propellers) stays the aircraft's own."""
    key, mine = _engine_block(fm)
    _, theirs = _engine_block(donor)
    if not mine or not theirs or (mine["Main"]["Type"] == "Jet") != (theirs["Main"]["Type"] == "Jet"):
        raise CdkError("This engine doesn't fit this aircraft")
    out = {}
    for block in ENGINE_BLOCKS:
        if isinstance(mine.get(block), dict) and isinstance(theirs.get(block), dict):
            out.update(_copied(mine[block], theirs[block], (key, block)))
    return out


HP_MULT = 1000.0
# "Unbreakable airframe": the flight model's breaking limits, raised (speeds km/h IAS, overloads in newtons)
NO_BREAK_SPEED = 100000.0
_BREAK_SPEEDS = {"Vne", "VNE", "VneHeli", "VneCockpitDoor", "CockpitOpenedDoorBreakSpeed", "GearDestructionIndSpeed",
                 "AirbrakeDestructionIndSpeed", "chuteRipSpeed"}
_BREAK_MACHS = {"VneMach", "MNE"}  # MNE: each wing's Mach limit (Strength), 0.96 on the F-14B (checked in game)
_BREAK_OVERLOADS = {"CritOverload", "WingCritOverload"}


def _structural_overrides(node, path=()) -> dict:
    """{path: (type, value)} raising every breaking limit of a flight model: wings torn off by speed or g
    (Vne / VneMach / Strength VNE and MNE, CritOverload / WingCritOverload), gear, flaps, airbrake, canopy, chute."""
    out = {}
    if not isinstance(node, dict):
        return out
    for k, v in node.items():
        p = path + (k,)
        if isinstance(v, dict):
            out.update(_structural_overrides(v, p))
        elif isinstance(v, bool):
            continue
        elif k in _BREAK_SPEEDS and isinstance(v, (int, float)) and v > 0:
            out[p] = ("r", NO_BREAK_SPEED)
        elif k in _BREAK_MACHS and isinstance(v, (int, float)):
            out[p] = ("r", 100.0)
        elif k in _BREAK_OVERLOADS and isinstance(v, list) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
            out[p] = ("p2", [float(v[0]) * 100.0, float(v[1]) * 100.0])
        elif k.startswith("FlapsDestructionIndSpeed") and isinstance(v, list) and len(v) == 2:
            out[p] = ("p2", [float(v[0]), NO_BREAK_SPEED])
    return out


def _power_overrides(fm: dict, mul: float) -> dict:
    """{path: (type, value)} multiplying an aircraft's engine output: jets their thrust table base (ThrustMax0),
    piston engines their power (Main/Power and the compressor's Power<n> / PowerConstRPM<n> / PowerAtCeiling<n>)."""
    out = {}
    for ek, e in (fm or {}).items():
        if not (ek.startswith("Engine") and isinstance(e, dict) and isinstance(e.get("Main"), dict)):
            continue
        main = e["Main"]
        base = (main.get("ThrustMax") or {}).get("ThrustMax0") if isinstance(main.get("ThrustMax"), dict) else None
        if main.get("Type") == "Jet":
            if isinstance(base, (int, float)) and base > 0:
                out[(ek, "Main", "ThrustMax", "ThrustMax0")] = ("r", float(base) * mul)
            continue
        if isinstance(main.get("Power"), (int, float)) and main["Power"] > 0:
            out[(ek, "Main", "Power")] = ("r", float(main["Power"]) * mul)
        comp = e.get("Compressor")
        for k, v in (comp.items() if isinstance(comp, dict) else ()):
            if re.fullmatch(r"(Power|PowerConstRPM|PowerAtCeiling)\d+", k) and isinstance(v, (int, float)) and v > 0:
                out[(ek, "Compressor", k)] = ("r", float(v) * mul)
    return out


def _handling_overrides(fm: dict) -> dict:
    """{path: (type, value)} for an aircraft that turns, rolls and pitches far better (super mobility): moment of
    inertia x0.4, control surfaces x1.5 in area, x2 in deflection rate and in the speed up to which they stay
    effective, the wing's maximum lift x1.3 (old flight models: NoFlaps / FullFlaps; recent: WingPlane* /
    FlapsPolar*), every minimum drag coefficient (CdMin) x0.5."""
    out = {}

    def num(v):
        return isinstance(v, (int, float)) and not isinstance(v, bool)

    def scaled(v, k):
        if num(v):
            return ("r", float(v) * k)
        if isinstance(v, list) and len(v) in (2, 3) and all(num(x) for x in v):
            return ("p2" if len(v) == 2 else "p3", [float(x) * k for x in v])
        return None

    def walk(n, path):
        for k, v in n.items():
            p = path + (k,)
            if isinstance(v, dict):
                walk(v, p)
                continue
            mul = None
            if p == ("MomentOfInertia",):
                mul = 0.4
            elif len(p) == 1 and k in ("AileronEffectiveSpeed", "RudderEffectiveSpeed", "ElevatorsEffectiveSpeed",
                                       "AileronMaxDv", "ElevatorMaxDv", "RudderMaxDv"):
                mul = 2.0
            elif len(p) >= 2 and p[-2] == "Areas" and k in ("Aileron", "Elevator", "Rudder"):
                mul = 1.5
            elif p[0] == "Aerodynamics" and k == "CdMin":
                mul = 0.5
            elif p[0] == "Aerodynamics" and k in ("ClCritHigh", "ClCritLow") and (
                    any(x in ("NoFlaps", "FullFlaps") for x in p)
                    or (any(x.startswith("WingPlane") for x in p) and any(x.startswith("FlapsPolar") for x in p))):
                mul = 1.3
            got = scaled(v, mul) if mul else None
            if got:
                out[p] = got

    walk(fm or {}, ())
    return out


def _write_tree(b: "Blk", tree: dict):
    """Writes {path: (type, value)} as nested @override blocks ("+<type>": a new value, written as is)."""
    groups: dict = {}
    for path, tv in tree.items():
        if len(path) == 1:
            typ, v = tv
            if typ.startswith("+"):
                b.line(f"{path[0]}:{typ[1:]}={_blk_value(typ[1:], v)}")
            else:
                b.line(f'"@override:{path[0]}":{typ}={_blk_value(typ, v)}')
        else:
            groups.setdefault(path[0], {})[path[1:]] = tv
    for name, sub in groups.items():
        b.open(name)
        _write_tree(b, sub)
        b.close()


def _has_hp(node) -> bool:
    if isinstance(node, dict):
        return any(k == "hp" or _has_hp(v) for k, v in node.items())
    return False


def _damage_overrides(b: "Blk", node: dict, mult: float):
    """Multiplies every hit-point value of the damage model (DamageParts)."""
    for k, v in node.items():
        if k == "hp" and isinstance(v, (int, float)) and not isinstance(v, bool):
            if isinstance(v, int):
                b.int("hp", min(int(v * mult), 2_000_000_000))
            else:
                b.real("hp", v * mult)
        elif isinstance(v, dict) and _has_hp(v):
            b.open(k)
            _damage_overrides(b, v, mult)
            b.close()


def build_files(vid: str, cat: str, details: dict, mods: dict, host: str, pylons: dict | None,
                air_method: str = "custom", unit_data: dict | None = None,
                catalog: dict | None = None, tag: str = "", fm_data: dict | None = None,
                engine_fm: dict | None = None) -> tuple[dict[str, str], str, str, str]:
    """Returns ({path under the package: text}, weapons preset or "", mission unit_class, package dir).
    tag: names the files and the unit after it instead of the vehicle id (AI units: "<id>_ai1"…).
    fm_data: the aircraft's flight model (datamine), for mods["noStructural"] (unbreakable airframe)."""
    flyer = cat in ("air", "heli")
    custom_name = flyer and air_method == "custom"
    name = tag or vid
    if not SAFE.match(vid) or not SAFE.match(name) or (not custom_name and not SAFE.match(host or "")):
        raise CdkError("Invalid vehicle or host id")
    mods = mods or {}
    st = details.get("st") or {}
    files: dict[str, str] = {}
    unit_dir = _unit_dir(cat)
    game_data = game_data_root()
    if custom_name:
        unit_class = f"wtftd_{name}".lower()
        host_path = f"{unit_dir}/{unit_class}.blk"
        pkg = "pkg_user"
    else:
        unit_class = f"userVehicles/{host}"
        host_path = f"{unit_dir}/userVehicles/{host}.blk"
        pkg = "pkg_local"
    b = _header(vid, f"{unit_dir}/{vid}.blk")
    preset = ""

    if cat == "ground":
        hp = _num(mods, "hp", 1, 100000)
        rpm = _num(mods, "rpm", 100, 100000)
        mass = _num(mods, "mass", 100, 1_000_000)
        brake = _num(mods, "brake", 1, 100_000_000)
        speed_mul = _num(mods, "speedMul", 0.1, 10)
        if hp or rpm or mass or brake or speed_mul:
            b.open("VehiclePhys")
            if hp or rpm:
                b.open("engine")
                if hp:
                    b.real("horsePowers", hp)
                if rpm:
                    b.real("maxRPM", rpm)
                b.close()
            if mass:
                b.open("Mass")
                b.real("Empty", mass)
                b.real("TakeOff", mass + float(st.get("fuel", 0)))
                b.close()
            if brake or (speed_mul and st.get("gear")):
                b.open("mechanics")
                if brake:
                    b.real("maxBrakeForce", brake)
                if speed_mul and st.get("gear"):
                    b.real("mainGearRatio", float(st["gear"]) / speed_mul)
                b.close()
            b.close()

    # main gun (ground) / guns listed directly in commonWeapons
    groups = details.get("am") or []
    weapon_overrides = []
    for gi, g in enumerate(groups):
        if not g.get("wi"):
            continue
        gm = (mods.get("guns") or {}).get(str(gi)) or {}
        yaw = _num(gm, "yaw", 0.1, 1000)
        pitch = _num(gm, "pitch", 0.1, 1000)
        cap = _num(gm, "cap", 1, 100000)
        reload_s = _num(gm, "reload", 0.01, 600)
        if reload_s is None and mods.get("noReload") and g.get("sf") and g["sf"] < 20:
            reload_s = 0.05  # "No reload" cheat: near-instant reload on every gun we can reach
        shells = _clean_shells(gm.get("shells"), g)
        wfile = ""
        if (reload_s or shells) and g.get("p"):
            wname = f"{name}_w{g['wi']}".lower()
            wfile = f"{game_data}/Weapons/wtftd/{wname}.blk"
            wb = _header(f"{vid} weapon {g['wi']}", g["p"])
            if reload_s:
                wb.real("shotFreq", 1.0 / reload_s)
            for sid, sm in shells.items():
                if sid == "":
                    _shell_block(wb, sm)
                else:
                    wb.open(sid)
                    _shell_block(wb, sm)
                    wb.close()
            files[wfile] = str(wb)
        swap = (catalog or {}).get(str(gm.get("swap") or "")) or {}
        if "models_weapons" in str(swap.get("p", "")).lower():  # another ground or ship weapon in its place
            wfile = swap["p"]
        if yaw or pitch or cap or wfile:
            weapon_overrides.append((g["wi"], yaw, pitch, cap, wfile))
    if weapon_overrides:
        b.open("commonWeapons")
        for wi, yaw, pitch, cap, wfile in weapon_overrides:
            b.open(f"Weapon[{wi}]")
            if yaw:
                b.real("speedYaw", yaw)
            if pitch:
                b.real("speedPitch", pitch)
            if cap:
                b.int("bullets", cap)
            if wfile:
                b.text("blk", wfile)
            b.close()
        b.close()

    _voices(b, mods, unit_data)
    if cat in ("air", "heli"):
        _sensors(b, details, mods, unit_data)
        _avionics(b, mods, unit_data)
        mass = _num(mods, "mass", 10, 1_000_000)
        fuel = _num(mods, "fuel", 0, 1_000_000)
        thrust_mul = _num(mods, "thrustMul", 0.05, 20)
        tboost = _num(mods, "tboost", 0.1, 20)
        abboost = _num(mods, "abboost", 0.1, 20)
        # always wrap the flight model: the unit file now lives in userVehicles/, and a relative
        # fmFile could otherwise be looked up next to it and not be found
        if st.get("fm"):
            fm_name = f"wtftd_{name}".lower()
            fb = _header(f"{vid} flight model", f"{game_data}/flightModels/{st['fm']}")
            tree: dict = {}  # {path: (type, value)}, one block per section
            if isinstance(fm_data, dict) and isinstance(engine_fm, dict):
                tree.update(_engine_overrides(fm_data, engine_fm))
            if mods.get("noStructural") and isinstance(fm_data, dict):
                tree.update(_structural_overrides(fm_data))
            if mods.get("superMobility") and isinstance(fm_data, dict):
                # super mobility (aircraft): handling (roll, pitch, turn, drag), engine output x3, 40 % lighter
                tree.update(_handling_overrides(fm_data))
                if not thrust_mul:
                    tree.update(_power_overrides(fm_data, 3.0))
                if not mass and st.get("mass"):
                    tree[("Mass", "EmptyMass")] = ("r", float(st["mass"]) * 0.6)
            if mass:
                tree[("Mass", "EmptyMass")] = ("r", mass)
            if fuel is not None:
                tree[("Mass", "MaxFuelMass0")] = ("r", fuel)
            if thrust_mul and st.get("thrust"):
                tree[("EngineType0", "Main", "Thrust")] = ("r", float(st["thrust"]) * thrust_mul)
            if thrust_mul and isinstance(fm_data, dict):
                # jets: the game takes the maximum thrust from the ThrustMax table (ThrustMax0 x coefficients by
                # altitude / speed), not from Main/Thrust (checked in game 2026-10-09): that base, every engine type
                for et, e in fm_data.items():
                    base = ((e.get("Main") or {}).get("ThrustMax") or {}).get("ThrustMax0") if isinstance(e, dict) and et.startswith("EngineType") else None
                    if isinstance(base, (int, float)) and not isinstance(base, bool) and base > 0:
                        tree[(et, "Main", "ThrustMax", "ThrustMax0")] = ("r", float(base) * thrust_mul)
            if tboost:
                tree[("EngineType0", "Main", "ThrottleBoost")] = ("r", tboost)
            if abboost:
                tree[("EngineType0", "Main", "AfterburnerBoost")] = ("r", abboost)
            _write_tree(fb, tree)
            text = str(fb)
            # fmFile may be resolved from flightModels/ or next to the unit file: provide both
            files[f"{game_data}/flightModels/fm/{fm_name}.blk"] = text
            if not custom_name:
                files[f"{game_data}/flightModels/userVehicles/fm/{fm_name}.blk"] = text
            b.text("fmFile", f"fm/{fm_name}.blk")

        # aircraft with fixed presets only: "lp" = their attachment points (emitters), taken from those presets
        legacy = {s["i"]: s for s in details.get("lp", [])} if not details.get("sl") else {}
        emitters = {s["i"]: s.get("e") for s in details.get("sl") or details.get("lp") or []}
        chosen, extras = [], []
        variants: dict[tuple, str] = {}  # (weapon file, its changes) -> modified copy
        tubes: set[str] = set()  # those of them that are containers
        raw: list[tuple] = []  # aircraft without pylons: plain weapons in the loadout
        if pylons:
            slots = {str(s["i"]): {o["n"] for o in s["o"]} for s in details.get("sl") or details.get("lp") or []}
            for k, v in pylons.items():
                if isinstance(v, str) and v and str(k) in slots and v in slots[str(k)]:
                    lp = legacy.get(int(k))
                    if lp:  # the official weapons of that point, as the game's preset hangs them
                        o = next(x for x in lp["o"] if x["n"] == v)
                        raw += [(trig, blk, lp["e"], bullets) for trig, blk, bullets in o.get("r", [])
                                if SAFE.match(str(blk).replace("/", "_").replace(".", "_")) and SAFE.match(str(trig).replace(" ", "_"))]
                    else:
                        chosen.append((int(k), v))  # official option of that pylon
                elif isinstance(v, dict) and str(k).isdigit() and emitters.get(int(k)):
                    w = (catalog or {}).get(str(v.get("w", "")))
                    if w and SAFE.match(str(v.get("w"))):
                        n = max(1, min(int(v.get("n") or 1), 8))
                        what = f"{vid} {v.get('w')}"
                        custom = _air_copy(w, what, v.get("mod")) if w.get("air") else _custom_weapon(w, v.get("mod"), what)
                        if w.get("air") and not custom:
                            continue
                        if custom:  # the same weapon, modified: a file of its own that the pylon uses instead
                            # one file per weapon + changes: pylons with the same one fire one after the other
                            # (different files would fire together), and named as the game's own so the game
                            # shows its name (weapons/<file name>)
                            key = (w["p"], custom.split("\n", 1)[1])  # without the header line (its time)
                            if key not in variants:
                                stem = w["p"].replace("\\", "/").rsplit("/", 1)[-1]
                                variants[key] = f"{game_data}/Weapons/wtftd/{name.lower()}_{len(variants) + 1}/{stem}"
                                files[variants[key]] = custom
                                tube = _in_tube(variants[key], custom) if w.get("air") else None
                                if tube:
                                    files.update(tube)
                                    tubes.add(variants[key])
                            w = dict(w, p=variants[key], pod=variants[key] in tubes)
                        extras.append((int(k), w, emitters[int(k)], n))  # any weapon of the game on that pylon
        # Aircraft with pylons (WeaponSlots) only take "slot + preset" entries in a loadout: a bare
        # Weapon{trigger, blk, emitter} there is ignored by the game. So each non-standard weapon
        # becomes a new WeaponPreset of its pylon (added to the unit file), picked by slot + preset.
        wslots = _weapon_slots(unit_data)
        slot_weapons: dict[int, list[tuple]] = {}  # slot -> [(trigger, blk, emitter, bullets)]
        for k, w, emitter, n in extras:
            bullets = None if w.get("pod") else n * w.get("gun", 1)
            if k in wslots:
                bomb_em = wslots[k][1] if w["t"] == "bombs" else ""
                slot_weapons.setdefault(k, []).append((w["t"], w["p"], bomb_em or emitter, bullets))
            else:
                raw.append((w["t"], w["p"], emitter, bullets))
        if chosen or slot_weapons or raw:
            if True:
                pname = f"wtftd_{name}".lower()
                pb = Blk()
                pb.line(f"{MARKER} - {vid} custom loadout")
                for idx, name in sorted(chosen) + [(k, f"wtftd_slot{k}") for k in sorted(slot_weapons)]:
                    pb.line("Weapon{")
                    pb.line(f"  slot:i={idx}")
                    pb.line(f'  preset:t="{name}"')
                    pb.line("}")
                for weapon in raw:
                    for line in _weapon_lines(*weapon):
                        pb.line(line)
                if slot_weapons:
                    b.open("WeaponSlots")
                    for k, weapons in sorted(slot_weapons.items()):
                        b.open(f"WeaponSlot[{wslots[k][0]}]")
                        b.line("WeaponPreset{")
                        b.line(f'  name:t="wtftd_slot{k}"')
                        for weapon in weapons:
                            for line in _weapon_lines(*weapon, ind="  ", separate=True):
                                b.line(line)
                        b.line("}")
                        b.close()
                    b.close()
                files[f"{game_data}/flightModels/weaponPresets/{pname}.blk"] = str(pb)
                b.line('"@override:weapon_presets"{')
                b.line("  preset{")
                b.line(f'    name:t="{CUSTOM_PRESET}"')
                b.line(f'    blk:t="{game_data}/flightModels/weaponPresets/{pname}.blk"')
                b.line("  }")
                b.line("}")
                preset = CUSTOM_PRESET

    if mods.get("invulnerable") and isinstance((unit_data or {}).get("DamageParts"), dict):
        b.open("DamageParts")
        _damage_overrides(b, unit_data["DamageParts"], HP_MULT)
        b.close()

    files[host_path] = str(b)
    return files, preset, unit_class, pkg


# --------------------------------------------------------------------------- disk

def _content(game_dir: Path) -> Path:
    return (game_dir / "content").resolve()


def _manifest_path(user_dir: Path) -> Path:
    return user_dir / "cdk_manifest.json"


def read_manifest(user_dir: Path) -> list[str]:
    try:
        data = json.loads(_manifest_path(user_dir).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    out = []
    for p in data:
        if isinstance(p, str):
            out.append(p if p.split("/", 1)[0] in PACKAGES else f"pkg_local/{p}")  # older manifests
    return out


def _safe_target(content: Path, rel: str) -> Path:
    target = (content / rel).resolve()
    if not any((content / pkg).resolve() in target.parents for pkg in PACKAGES):
        raise CdkError("Refusing to write outside content/pkg_local or content/pkg_user")
    return target


def write_files(game_dir: Path, user_dir: Path, files: dict[str, str], pkg: str = "pkg_local") -> list[str]:
    if pkg not in PACKAGES:
        raise CdkError("Invalid package")
    content = _content(game_dir)
    manifest = set(read_manifest(user_dir))
    written = []
    for rel, text in files.items():
        # the same game path in another package would shadow this one (pkg_local wins over pkg_user):
        # drop our stale copy there
        for other in PACKAGES:
            stale = f"{other}/{rel}"
            if other != pkg and stale in manifest:
                try:
                    _safe_target(content, stale).unlink()
                except (OSError, CdkError):
                    pass
                manifest.discard(stale)
        entry = f"{pkg}/{rel}"
        target = _safe_target(content, entry)
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            try:
                head = target.read_text(encoding="utf-8", errors="ignore")[:200]
            except OSError:
                head = ""
            if MARKER not in head:  # not ours (e.g. Ask3lad's file): keep a copy
                backup = user_dir / "backup" / f"{time.strftime('%Y%m%d-%H%M%S')}_{target.name}"
                backup.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(target, backup)
        target.write_text(text, encoding="utf-8")
        manifest.add(entry)
        written.append(entry)
    user_dir.mkdir(exist_ok=True)
    _manifest_path(user_dir).write_text(json.dumps(sorted(manifest), indent=1), encoding="utf-8")
    return written


def cleanup(game_dir: Path, user_dir: Path) -> int:
    """Removes every file WTFTD wrote under content/pkg_local and content/pkg_user, then empty folders."""
    content = _content(game_dir)
    removed = 0
    for entry in read_manifest(user_dir):
        try:
            target = _safe_target(content, entry)
        except CdkError:
            continue
        if target.is_file():
            try:
                target.unlink()
                removed += 1
            except OSError:
                pass
    for pkg in PACKAGES:
        root = content / pkg
        if not root.exists():
            continue
        for d in sorted((p for p in root.rglob("*") if p.is_dir()), key=lambda p: -len(p.parts)):
            try:
                d.rmdir()  # only succeeds when empty
            except OSError:
                pass
        try:
            root.rmdir()
        except OSError:
            pass
    try:
        _manifest_path(user_dir).unlink()
    except OSError:
        pass
    return removed


def status(game_dir: Path | None, user_dir: Path) -> dict:
    files = read_manifest(user_dir)
    present = sum(1 for f in files if (game_dir / "content" / f).exists()) if game_dir else 0
    return {"files": files, "present": present}
